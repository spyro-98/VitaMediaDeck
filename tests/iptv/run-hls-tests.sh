#!/usr/bin/env bash
set -euo pipefail
vmd_root="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$vmd_root"
vmd_ffmpeg="${VMD_IPTV_FFMPEG_ROOT:?Host FFmpeg 6 built with HLS and tools/ffmpeg-hls-custom-io.patch}"
vmd_fixture="${VMD_HLS_FIXTURE:?Directory generated by make-hls-fixtures.py}"
vmd_output="$(mktemp -d "${TMPDIR:-/tmp}/vmd-hls-check.XXXXXX")"
vmd_flags=(-O1 -g -Wall -Wextra -Isrc "-I$vmd_ffmpeg")
vmd_sources=(src/network/hls_manifest.c src/network/hls_source.c src/network/iptv_manifest.c src/network/iptv_source.c src/network/iptv_session.c)
vmd_libs=("$vmd_ffmpeg/libavformat/libavformat.a" "$vmd_ffmpeg/libavcodec/libavcodec.a" "$vmd_ffmpeg/libavutil/libavutil.a" -lxml2 -lpthread -lm)
for vmd_sanitizer in address,undefined thread; do
    clang "${vmd_flags[@]}" "-fsanitize=$vmd_sanitizer" tests/iptv/hls_manifest_test.c \
        src/network/hls_manifest.c src/network/iptv_manifest.c -lxml2 -o "$vmd_output/manifest-test"
    "$vmd_output/manifest-test"
    clang "${vmd_flags[@]}" "-fsanitize=$vmd_sanitizer" tests/iptv/hls_demux_test.c \
        "${vmd_sources[@]}" "${vmd_libs[@]}" -o "$vmd_output/demux-test"
    for vmd_name in plain mux negative separate range maprange implicit explicit rotation nodelay nodelay-mux; do
        "$vmd_output/demux-test" "$vmd_fixture" "$vmd_name.m3u8"
    done
    clang "${vmd_flags[@]}" "-fsanitize=$vmd_sanitizer" tests/iptv/hls_lifecycle_test.c \
        "${vmd_sources[@]}" "${vmd_libs[@]}" -o "$vmd_output/lifecycle-test"
    "$vmd_output/lifecycle-test" "$vmd_fixture"
done
printf 'HLS host test artifacts: %s\n' "$vmd_output"
